const ADDRESSES_URL = new URL('../assets/data/ph_addresses.json', import.meta.url).href;
let addresses = null;

// Loaded once, on first use (about 0.5 MB).
export function loadPhAddresses() {
  addresses ||= fetch(ADDRESSES_URL).then((response) => {
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return response.json();
  }).catch((error) => {
    addresses = null;
    throw error;
  });
  return addresses;
}
